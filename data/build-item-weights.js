/**
 * Item weights (lb) from 5etools base items and items, for the Encumbrance panel.
 * Run: node data/build-item-weights.js → data/item_weights.js
 *
 * ITEM_WEIGHTS maps a lower-case item name to its weight, or to { 2014, 2024 } when the
 * two editions disagree (Explorer's Pack is 59 lb in the 2014 PHB, 55 lb in the 2024 PHB).
 */

const fs = require('fs');
const path = require('path');

const SRC = 'C:\\Users\\Kiana\\Downloads\\5etools-src-main\\data';
const J = f => JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));

const is2024 = it => it.edition === 'one' || /^X(PHB|DMG|MM)$/.test(it.source);
const all = [...J('items-base.json').baseitem, ...J('items.json').item].filter(it => typeof it.weight === 'number');

const byName = {};
for (const it of all) {
  const key = it.name.toLowerCase();
  const e = byName[key] = byName[key] || {};
  const ed = is2024(it) ? '2024' : '2014';
  // First source wins within an edition; core books are listed first in 5etools
  if (e[ed] === undefined || ['PHB', 'XPHB'].includes(it.source)) e[ed] = it.weight;
}

const out = {};
for (const [name, e] of Object.entries(byName).sort(([a], [b]) => a.localeCompare(b))) {
  const w14 = e['2014'] ?? e['2024'], w24 = e['2024'] ?? e['2014'];
  out[name] = w14 === w24 ? w14 : { 2014: w14, 2024: w24 };
}

const header = '// Generated by data/build-item-weights.js from 5etools — do not edit by hand.\n';
fs.writeFileSync(path.join(__dirname, 'item_weights.js'), header + 'const ITEM_WEIGHTS = ' + JSON.stringify(out) + ';\n');
console.log(`${Object.keys(out).length} item weights written`);
