/**
 * Damage cantrips from the 5etools spell data, for attack rows that scale with character level.
 * Run: node data/build-cantrip-damage.js → data/cantrip_damage.js
 *
 * CANTRIP_DAMAGE['2024' | '2014'][name] = { dice: [lv1, lv5, lv11, lv17], type, attack, save, extra, beams }
 * Only cantrips that make their own attack roll or saving throw are included; weapon cantrips
 * (Booming Blade, Green-Flame Blade, Shillelagh, True Strike) change a weapon attack instead.
 */

const fs = require('fs');
const path = require('path');

const SRC = 'C:\\Users\\Kiana\\Downloads\\5etools-src-main\\data\\spells';
const SAVES = { strength: 'str', dexterity: 'dex', constitution: 'con', intelligence: 'int', wisdom: 'wis', charisma: 'cha' };
const TIERS = [1, 5, 11, 17];
// Second damage lines, reworded for the attack table
const EXTRA_LABELS = { 'Toll the Dead': 'if it is hurt' };
const SKIP = new Set(['Booming Blade', 'Green-Flame Blade', 'Shillelagh', 'True Strike', 'Magic Stone']);

// Highest listed level at or below each tier ({"1":"1d8","5":"2d8",...} → ['1d8','2d8','3d8','4d8'])
const tierDice = scaling => TIERS.map(t => {
  const lv = Object.keys(scaling).map(Number).filter(l => l <= t).sort((a, b) => b - a)[0];
  return lv === undefined ? null : scaling[lv];
});

const out = { 2024: {}, 2014: {} };
for (const f of fs.readdirSync(SRC).filter(f => /^spells-.*\.json$/.test(f))) {
  const ed = f === 'spells-xphb.json' ? '2024' : '2014';
  for (const s of JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8')).spell || []) {
    if (s.level !== 0 || !s.damageInflict || SKIP.has(s.name)) continue;
    const attack = !!(s.spellAttack && s.spellAttack.length);
    const save = s.savingThrow && s.savingThrow.length ? SAVES[s.savingThrow[0]] : null;
    if (!attack && !save) continue;
    const type = s.damageInflict.length > 1 ? '(choose type)' : s.damageInflict[0];
    const e = { type, attack, save };
    if (s.name === 'Eldritch Blast') {
      e.dice = ['1d10', '1d10', '1d10', '1d10']; e.beams = true;
    } else {
      const lines = [].concat(s.scalingLevelDice || []);
      if (!lines.length) continue;
      e.dice = tierDice(lines[0].scaling);
      if (lines[1] && EXTRA_LABELS[s.name]) e.extra = { dice: tierDice(lines[1].scaling), label: EXTRA_LABELS[s.name] };
    }
    if (e.dice.some(d => !d)) continue;
    if (!e.save) delete e.save;
    out[ed][s.name] = e;
  }
}

const sorted = o => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const body = `// Generated by data/build-cantrip-damage.js from 5etools. Do not edit by hand.
const CANTRIP_DAMAGE = ${JSON.stringify({ 2024: sorted(out[2024]), 2014: sorted(out[2014]) }, null, 1)};
if (typeof module !== 'undefined') module.exports = { CANTRIP_DAMAGE };
`;
fs.writeFileSync(path.join(__dirname, 'cantrip_damage.js'), body);
console.log(`cantrip_damage.js: ${Object.keys(out[2024]).length} (2024) + ${Object.keys(out[2014]).length} (2014) cantrips`);
